'use client';

import { useEffect, useState } from 'react';
import RegistrationForm, { Field, FormSection } from './RegistrationForm';

const fieldsToSend = [
  'patientName',
  'dateOfBirth',
  'gender',
  'phone',
  'email',
  'address',
  'registrationDate',
  'doctor',
  'service',
  'testCode',
  'status',
];

export default function PatientRegistrationForm() {
  const [tests, setTests] = useState([]);
  const [testsError, setTestsError] = useState('');
  const [isLoadingTests, setIsLoadingTests] = useState(true);
  const [selectedTest, setSelectedTest] = useState(null);

  useEffect(() => {
    let isCurrent = true;

    return async function() {
    try {
        let t = await fetch("/api/tests");
        
        // Check if the response is actually JSON before parsing
        const contentType = t.headers.get("content-type");
        if (!t.ok || !contentType || !contentType.includes("application/json")) {
            const errorText = await t.text(); // Get raw text from the 502 error
            throw Error(`Server Error (${t.status}): ${errorText || "Invalid response"}`);
        }

        let a = await t.json();
        e && l(a.tests);
    } catch (t) {
        e && n(t instanceof Error ? t.message : "Could not load tests.");
    } finally {
        e && o(!1);
    }
}();

  
   
  }, []);

  function selectTest(event) {
    const test = tests.find((item) => item.testName === event.target.value);
    setSelectedTest(test || null);
  }

  return (
    <RegistrationForm
      saveLabel="Save patient details"
      apiEndpoint="/api/patients"
      fieldsToSend={fieldsToSend}
    >
      <FormSection title="Personal information">
        <Field label="Patient ID" name="patientId" placeholder="Generated by system" disabled helper="Will be generated by the backend" />
        <Field label="Full name" name="patientName" placeholder="Enter patient's full name" required />
        <Field label="Date of birth" name="dateOfBirth" type="date" />
        <Field label="Gender" name="gender" required options={['Female', 'Male', 'Prefer not to say']} />
        <Field label="Phone number" name="phone" type="tel" placeholder="03XX XXXXXXX" required />
        <Field label="Email address" name="email" type="email" placeholder="patient@example.com" />
        <Field label="Residential address" name="address" type="textarea" placeholder="House, street, area, city" full />
      </FormSection>
      <hr className="form-divider" />
      <FormSection title="Registration & test details">
        <Field label="Registration date" name="registrationDate" type="date" required />
        <Field
          label="Required test / service"
          name="service"
          options={tests.map((test) => test.testName)}
          onChange={selectTest}
          disabled={isLoadingTests || tests.length === 0}
          helper={
            testsError ||
            (isLoadingTests
              ? 'Loading tests...'
              : tests.length === 0
                ? 'No tests found in the Labora.Tests collection.'
                : '')
          }
        />
        <Field label="Test code" name="testCode" value={selectedTest?.testCode ?? ''} readOnly />
        <Field label="Doctor name" name="doctorDisplay" value={selectedTest?.doctorName ?? ''} disabled />
        <input type="hidden" name="doctor" value={selectedTest?.doctorName ?? ''} />
        <Field label="Patient status" name="status" options={['Active', 'Pending', 'Completed', 'Inactive']} />
      </FormSection>
    </RegistrationForm>
  );
}
